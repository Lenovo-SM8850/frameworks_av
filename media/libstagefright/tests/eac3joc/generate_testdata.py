"""Regenerates Eac3JocDetectorTestData.h from the CTS Atmos stream and FFmpeg-made streams.

Run from a source tree with ANDROID_BUILD_TOP set and FFmpeg on the path.
"""
import os
import pathlib
import random
import subprocess
import tempfile

JOC_RAW = (pathlib.Path(os.environ["ANDROID_BUILD_TOP"])
           / "cts/tests/tests/media/audio/res/raw/Living_Room_Atmos_6ch_640kbps_eac3_joc_10s.raw")
OUT = pathlib.Path(__file__).resolve().parent / "Eac3JocDetectorTestData.h"

AC3_FRAME_WORDS = {
    0: [64, 64, 80, 80, 96, 96, 112, 112, 128, 128, 160, 160, 192, 192, 224,
        224, 256, 256, 320, 320, 384, 384, 448, 448, 512, 512, 640, 640, 768,
        768, 896, 896, 1024, 1024, 1152, 1152, 1280, 1280],
    1: [69, 70, 87, 88, 104, 105, 121, 122, 139, 140, 174, 175, 208, 209, 243,
        244, 278, 279, 348, 349, 417, 418, 487, 488, 557, 558, 696, 697, 835,
        836, 975, 976, 1114, 1115, 1253, 1254, 1393, 1394],
    2: [96, 96, 120, 120, 144, 144, 168, 168, 192, 192, 240, 240, 288, 288,
        336, 336, 384, 384, 480, 480, 576, 576, 672, 672, 768, 768, 960, 960,
        1152, 1152, 1344, 1344, 1536, 1536, 1728, 1728, 1920, 1920],
}


def eac3_frames(data, count):
    frames = []
    pos = 0
    while len(frames) < count:
        sync = data.find(b"\x0b\x77", pos)
        assert sync >= 0, "missing syncword"
        frmsiz = ((data[sync + 2] & 0x07) << 8) | data[sync + 3]
        size = (frmsiz + 1) * 2
        assert sync + size <= len(data), "truncated frame"
        frames.append(data[sync:sync + size])
        pos = sync + size
    return b"".join(frames)


def ac3_frames(data, count):
    frames = []
    pos = 0
    while len(frames) < count:
        sync = data.find(b"\x0b\x77", pos)
        assert sync >= 0, "missing syncword"
        header = data[sync:sync + 5]
        fscod = header[4] >> 6
        frmsizecod = header[4] & 0x3F
        size = AC3_FRAME_WORDS[fscod][frmsizecod] * 2
        assert sync + size <= len(data), "truncated frame"
        frames.append(data[sync:sync + size])
        pos = sync + size
    return b"".join(frames)


def emit(name, data):
    lines = [f"constexpr uint8_t {name}[] = {{"]
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        plain = tmp / "plain51.eac3"
        ac3 = tmp / "plain.ac3"
        # Plain 5.1 DD+ without the JOC extension.
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-f", "lavfi",
             "-i", "sine=frequency=440:sample_rate=48000:duration=10",
             "-af", "pan=5.1|c0=c0|c1=c0|c2=c0|c3=c0|c4=c0|c5=c0",
             "-c:a", "eac3", "-b:a", "384k", "-f", "eac3", str(plain)], check=True)
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-f", "lavfi",
             "-i", "sine=frequency=440:duration=1", "-ar", "48000", "-ac", "6",
             "-c:a", "ac3", "-f", "ac3", str(ac3)], check=True)

        joc_data = eac3_frames(JOC_RAW.read_bytes(), 3)
        plain_data = eac3_frames(plain.read_bytes(), 3)
        ac3_data = ac3_frames(ac3.read_bytes(), 2)

    rng = random.Random(20261030)
    garbage = bytes(rng.choice([b for b in range(256) if b != 0x0B]) for _ in range(1024))

    body = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by generate_testdata.py; do not edit by hand.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        f"constexpr size_t kJocFrameSize = {len(joc_data) // 3};",
        "",
        emit("kJocFrames", joc_data),
        "",
        emit("kPlain51Frames", plain_data),
        "",
        emit("kAc3Frames", ac3_data),
        "",
        emit("kGarbage", garbage),
        "",
    ]
    OUT.write_text("\n".join(body))
    print("wrote", OUT, "joc", len(joc_data), "plain", len(plain_data),
          "ac3", len(ac3_data))


if __name__ == "__main__":
    main()
